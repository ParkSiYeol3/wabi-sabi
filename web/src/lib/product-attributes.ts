// 주의사항 — 자주 쓰는 문구(복수 선택). 대표님이 매번 직접 입력하던 두 문구
// ("식기세척기 사용 가능"·"전자레인지 및 오븐 사용 불가")를 프리셋에 추가(2026-09-05).
